// Bundle only the public synthetic pilot; never records or imports live conversations.
const fs = require('node:fs');
const path = require('node:path');
const { readJsonl, validateDataset } = require('./gatekeeper-replay.cjs');
const root = path.resolve(__dirname, '..');
const source = path.join(root, 'tests/fixtures/gatekeeper/pilot.jsonl');
const rows = readJsonl(source); validateDataset(rows);
if (rows.some(row => row.source !== 'synthetic')) throw Error('Only synthetic examples may enter the app bundle');
fs.writeFileSync(path.join(root, 'app/conversation-detection/gatekeeper-pilot.ts'),
  '// Generated by scripts/sync-gatekeeper-pilot.cjs from the public synthetic fixture.\n'
  + 'export const GATEKEEPER_PILOT = ' + JSON.stringify(rows, null, 2) + ';\n');
console.log(`Bundled ${rows.length} synthetic examples, pending human review.`);
